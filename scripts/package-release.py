#!/usr/bin/env python3
"""Package local sources and verified build artifacts. Never include .env or user workspaces."""
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import zipfile

ROOT = Path(__file__).resolve().parents[1]
EXCLUDED = {'.git', '.env', '.idea', '.vscode', '.local', '.angular',
            'AGENTS.md', '.agents', '.codex', 'node_modules', 'target', 'dist',
            'test-results', 'playwright-report', 'release', '__pycache__'}
SOURCE_DIRS = ['backend', 'frontend', 'infra', 'scripts', 'docs/performance', '.github']
ROOT_FILES = ['README.md', '.env.example', '.gitignore', '.editorconfig', '.nvmrc',
              'compose.yaml', 'compose.app.yaml', 'docs/README.md', 'docs/SPECIFICATION.md',
              'docs/ENVIRONNEMENT.md', 'docs/ARCHITECTURE.md', 'docs/DECISIONS.md',
              'docs/DONNEES.md', 'docs/INGESTION.md', 'docs/API.md', 'docs/IHM.md',
              'docs/EXPLOITATION.md', 'docs/TESTS.md', 'docs/PERFORMANCE.md', 'docs/LIVRAISON.md']


def sha256(path):
    digest = hashlib.sha256()
    with path.open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            digest.update(block)
    return digest.hexdigest()


def main():
    jar = ROOT / 'backend/target/messaging-0.0.1-SNAPSHOT.jar'
    web = ROOT / 'frontend/dist/bank-messaging/browser'
    if not jar.is_file() or not (web / 'index.html').is_file():
        raise SystemExit('Build backend and frontend before packaging; see docs/LIVRAISON.md.')
    files = {ROOT / name for name in ROOT_FILES}
    for name in SOURCE_DIRS:
        for path in (ROOT / name).rglob('*'):
            parts = path.relative_to(ROOT).parts
            if (any(part in EXCLUDED for part in parts) or '.log' in path.suffixes
                    or path.suffix == '.lck' or path.name == 'open-mq-explorer.sh' or path.is_symlink()
                    or (path.name.startswith('.env') and path.name != '.env.example')):
                continue
            if path.is_file():
                files.add(path)
    files.add(jar)
    files.update(path for path in web.rglob('*') if path.is_file() and not path.is_symlink())
    # Include the Angular licenses generated by the production build.
    files.update(path for path in web.parent.glob('*.txt') if path.is_file())
    manifest = {
        'createdAt': datetime.now(timezone.utc).isoformat(),
        'version': '0.0.1',
        'scope': 'Local delivery; no GitHub publication',
        'files': {str(path.relative_to(ROOT)): sha256(path) for path in sorted(files)},
    }
    output = ROOT / 'release'
    output.mkdir(exist_ok=True)
    archive = output / 'bank-messaging-0.0.1-local.zip'
    with zipfile.ZipFile(archive, 'w', zipfile.ZIP_DEFLATED) as package:
        for path in sorted(files):
            package.write(path, str(path.relative_to(ROOT)))
        package.writestr('MANIFEST.json', json.dumps(manifest, indent=2) + '\n')
    (output / 'SHA256SUMS').write_text(f'{sha256(archive)}  {archive.name}\n')
    print(f'Created {archive.name}: {len(files)} files, {archive.stat().st_size} bytes')


if __name__ == '__main__':
    main()
